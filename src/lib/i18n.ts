const translations: Record<string, Dict> = { ES, EN, FR }

export const availableLanguages = [
  { code: "ES", name: "Español" },
  { code: "EN", name: "English" },
  { code: "FR", name: "Français" },
]

export function useT() {
  const lang = useAppStore((s) => s.language)
  return (key: string) => translations[lang]?.[key] ?? ES[key] ?? key
}

/** Translate a role/tag using role.* keys; falls back to original. */
export function useRoleT() {
  const t = useT()
  return (role: string) => {
    const translated = t(`role.${role}`)
    return translated === `role.${role}` ? role : translated
  }
}
